// ─────────────────────────────────────────────────────────────────────────────
// 排行图：纯几何自绘
//
// ⚠️ 为什么不用绘图库、也不用宿主字体：
//   - go.mod 里没有任何绘图依赖，且本期禁止新增第三方依赖（硬约束 1），
//     golang.org/x/image 也不在依赖里。
//   - 用宿主字体（/usr/share/fonts）画中文在不同机器上结果不一致，
//     容器里没装字体就会画出空白方块 —— 报告图是推送给用户的产物，
//     不能"在我机器上是好的"。
//
// 所以这里用标准库 image/png + image/draw + 内置 5×7 点阵字模，
// 只画三样东西：标题条、排行横条、右侧数字。字模只覆盖 ASCII，
// 中文标题放在图外（由通知渠道的正文承载），避免造一套汉字点阵。
// ─────────────────────────────────────────────────────────────────────────────

const (
	chartWidth  = 640
	chartRowH   = 28
	chartPadTop = 44
	chartPadX   = 12
	// maxChartRows 图上最多画的行数：参考实现 是 min(limit, 5)。
	maxChartRows = domain.PlayReportTopMax
)

var (
	chartBg      = color.RGBA{R: 0x14, G: 0x17, B: 0x1c, A: 0xff}
	chartTitleBg = color.RGBA{R: 0x1f, G: 0x6f, B: 0xeb, A: 0xff}
	chartBarBg   = color.RGBA{R: 0x2a, G: 0x2f, B: 0x38, A: 0xff}
	chartBar     = color.RGBA{R: 0x4f, G: 0xa3, B: 0xff, A: 0xff}
	chartText    = color.RGBA{R: 0xe8, G: 0xea, B: 0xed, A: 0xff}
	chartDim     = color.RGBA{R: 0x9a, G: 0xa4, B: 0xb2, A: 0xff}
)

// renderReportChart 渲染排行图。**永不返回错误**。
//
// 绘图失败返回 nil 是刻意的：图是报告的附加品，生成失败不该让整份报告
// 失败 —— 用户宁可看到没有图的文字报告，也不要看到"报告生成失败"。
// 调用方把 nil 当"无图"处理即可（推送文案里仍会带上排行文字）。
func renderReportChart(res domain.PlayReportResult) []byte {
	users := res.Users
	if len(users) > maxChartRows {
		users = users[:maxChartRows]
	}
	rows := len(users)
	if rows == 0 {
		rows = 1
	}
	h := chartPadTop + rows*chartRowH + 16
	img := image.NewRGBA(image.Rect(0, 0, chartWidth, h))
	draw.Draw(img, img.Bounds(), &image.Uniform{chartBg}, image.Point{}, draw.Src)

	// 标题条 + 标题文字。
	draw.Draw(img, image.Rect(0, 0, chartWidth, chartPadTop-6),
		&image.Uniform{chartTitleBg}, image.Point{}, draw.Src)
	title := "WATCH REPORT  " + strconv.Itoa(res.Period) + "D"
	drawText(img, chartPadX, 8, title, chartText, 2)

	sub := "TOP " + strconv.Itoa(len(users)) + "  |  " +
		shortTime(res.Since) + " ~ " + shortTime(res.Until)
	drawText(img, chartPadX, chartPadTop+4, sub, chartDim, 1)

	// 找出最大播放次数作为横条长度基准；全为 0 时不画条（除零防护）。
	maxCount := 0
	for _, u := range users {
		if u.Count > maxCount {
			maxCount = u.Count
		}
	}

	barX := chartPadX + 40
	barMaxW := chartWidth - barX - 150
	y := chartPadTop + 24
	for i, u := range users {
		rowY := y + i*chartRowH
		drawText(img, chartPadX, rowY+4, strconv.Itoa(i+1), chartDim, 1)
		name := truncateASCII(u.UserName, 8)
		drawText(img, chartPadX+18, rowY+4, name, chartText, 1)

		if maxCount > 0 {
			w := u.Count * barMaxW / maxCount
			if w < 2 {
				w = 2
			}
			draw.Draw(img, image.Rect(barX, rowY+5, barX+barMaxW, rowY+17),
				&image.Uniform{chartBarBg}, image.Point{}, draw.Src)
			draw.Draw(img, image.Rect(barX, rowY+5, barX+w, rowY+17),
				&image.Uniform{chartBar}, image.Point{}, draw.Src)
		}
		// 右侧：次数 + 时长。
		right := strconv.Itoa(u.Count) + "x  " + formatDuration(u.WatchedSeconds)
		drawText(img, chartWidth-chartPadX-textWidth(right, 1), rowY+4, right, chartText, 1)
	}
	if len(users) == 0 {
		drawText(img, chartPadX+18, y+4, "NO PLAYBACK IN THIS PERIOD", chartDim, 1)
	}

	var buf bytes.Buffer
	if err := png.Encode(&buf, img); err != nil {
		return nil
	}
	return buf.Bytes()
}

// formatDuration 秒 → "1h23m" / "12m" / "40s"。中文单位留给正文，图里用 ASCII。
func formatDuration(secs int) string {
	if secs <= 0 {
		return "0s"
	}
	if secs >= 3600 {
		return strconv.Itoa(secs/3600) + "h" + strconv.Itoa((secs%3600)/60) + "m"
	}
	if secs >= 60 {
		return strconv.Itoa(secs/60) + "m"
	}
	return strconv.Itoa(secs) + "s"
}

// truncateASCII 按字符（ASCII 可见字符）截断，超长加省略号。
// 点阵字模只覆盖 ASCII，遇到非 ASCII 一律替换成 '?'，
// 免得按字节宽度算出的位置全错。
func truncateASCII(s string, n int) string {
	out := make([]rune, 0, n+1)
	for _, r := range s {
		if r < 0x20 || r > 0x7e {
			r = '?'
		}
		out = append(out, r)
		if len(out) >= n {
			break
		}
	}
	if len([]rune(s)) > n && len(out) >= n && n > 1 {
		out[n-1] = '.'
	}
	return string(out)
}

