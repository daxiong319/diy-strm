// glyphW 单个字符的像素宽（5 列 + 1 列间隔）。
const (
	glyphW     = 6
	glyphH     = 7
	glyphScale = 2
)

// textWidth 估算一段文字的像素宽度（scale 倍）。
func textWidth(s string, scale int) int {
	n := len([]rune(s))
	if n == 0 {
		return 0
	}
	// 最后一个字符不占间隔列。
	return (n*glyphW - 1) * scale
}

// drawText 在 (x, y) 处画一行文字。scale=1 时是 5×7 小字，scale=2 放大一倍。
//
// 超出画布右边界直接停笔：报告里的用户名可能很长，不裁会画到画布外，
// 而 image.RGBA 的 Set 越界虽然不 panic，但边界判断留在调用方更容易看懂。
func drawText(img *image.RGBA, x, y int, s string, c color.Color, scale int) {
	r, g, b, a := c.RGBA()
	col := color.RGBA{uint8(r >> 8), uint8(g >> 8), uint8(b >> 8), uint8(a >> 8)}
	px := x
	for _, ru := range s {
		if ru < 0x20 || ru > 0x7e {
			ru = '?'
		}
		glyph := font5x7[ru-0x20]
		for col5 := 0; col5 < 5; col5++ {
			bits := glyph[col5]
			for row := 0; row < 7; row++ {
				if bits&(1<<uint(row)) == 0 {
					continue
				}
				for dy := 0; dy < scale; dy++ {
					for dx := 0; dx < scale; dx++ {
						img.Set(px+col5*scale+dx, y+row*scale+dy, col)
					}
				}
			}
		}
		px += glyphW * scale
	}
}
