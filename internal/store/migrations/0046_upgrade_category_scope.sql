-- T27 C-8 · 洗版规则「适用分类」
--
-- 给 media_upgrade_rules 加一列，让洗版规则可以只作用于某些分类目录下的文件
-- （参考实现 的「适用二级分类」）。空串 = 不按分类筛选，是存量规则的默认值。
--
-- ⚠️ 刻意**不**加外键也不做引用完整性：存的是目录名（用户看得懂、改得动），
-- 不是 classify_primary_categories 的 slug。理由与该表的定位一致 ——
-- 分类目录的权威源是模板 JSON，这张投影表随时会被重投影覆盖，
-- 让用户的洗版规则依赖一张会被整批删掉重建的表，会出现「改了分类模板，
-- 洗版规则静默失效」这种没法排查的现象。
--
-- 所以这里是**弱引用**：用户把这个目录名从分类模板里删了，洗版规则会
-- 筛不到任何文件（表现是扫描结果为 0 条，用户一眼能看出来），
-- 而不会报错或悄悄退化成筛全库。

ALTER TABLE media_upgrade_rules ADD COLUMN category_scope TEXT NOT NULL DEFAULT '';